/**
 * The catalogue shape, with every leaf widened to `string`. `en` is declared `as const` so its
 * keys are exhaustively known, but translations obviously carry different text — this mapped type
 * keeps the key checking while allowing any value.
 */
type Translated<T> = { [K in keyof T]: T[K] extends string ? string : Translated<T[K]> };

export type Messages = Translated<typeof en>;
